import ForgeResolver from '@forge/resolver';
import * as authoring from '../usecases/testAuthoring.js';
import * as execution from '../usecases/testExecution.js';
import * as planning from '../usecases/testPlanning.js';
import * as coverage from '../usecases/testCoverage.js';
import * as summary from '../usecases/testSummary.js';
import { startTestPlanExecution } from '../usecases/testPlanExecution.js';
import { retestTestExecution } from '../usecases/testRetest.js';
import { getRunEvidence } from '../usecases/testEvidence.js';
import { testContext } from '../usecases/testContext.js';
import { withRequestCache } from '../lib/cache.js';
import { wrapWithHarness } from '../lib/harnessLogger.js';

const Resolver = ForgeResolver.default ?? ForgeResolver;
const resolver = new Resolver();
const cached = (fn) => (req) => withRequestCache(() => fn(req));

resolver.define('tm:context', cached(testContext));
resolver.define('tm:test:get', cached(authoring.getTest));
resolver.define('tm:test:saveDraft', cached(authoring.saveTestDraft));
resolver.define('tm:test:publish', cached(authoring.publishTestVersion));
resolver.define('tm:test:signVersion', cached(authoring.signTestVersion));
resolver.define('tm:test:finishVersion', cached(authoring.finishTestVersion));
resolver.define('tm:exec:get', cached(execution.getExecution));
resolver.define('tm:exec:addRun', cached(execution.addTestRun));
resolver.define('tm:run:recordStep', cached(execution.recordRunStep));
resolver.define('tm:run:attachEvidence', cached(execution.attachRunEvidence));
resolver.define('tm:run:removeEvidence', cached(execution.removeRunEvidence));
resolver.define('tm:run:getEvidence', cached(getRunEvidence));
resolver.define('tm:run:sign', cached(execution.signTestRun));
resolver.define('tm:run:notExecuted', cached(execution.closeRunNotExecuted));
resolver.define('tm:run:retryBug', cached(execution.retryRunBug));
resolver.define('tm:planning:get', cached(planning.getTestCollection));
resolver.define('tm:planning:saveDraft', cached(planning.saveTestCollectionDraft));
resolver.define('tm:planning:publish', cached(planning.publishTestCollection));
resolver.define('tm:planning:sign', cached(planning.signTestCollection));
resolver.define('tm:planning:lookup', cached(planning.lookupTestCollectionMember));
resolver.define('tm:plan:selectRuns', cached(planning.selectTestPlanRuns));
resolver.define('tm:plan:startExecution', cached(startTestPlanExecution));
resolver.define('tm:exec:retest', cached(retestTestExecution));
resolver.define('tm:coverage:test', cached(coverage.getTestCoverage));
resolver.define('tm:coverage:source', cached(coverage.getSourceCoverage));
resolver.define('tm:sources:resolve', cached(coverage.resolveTestSourceSelection));
resolver.define('tm:sources:decisions', cached(coverage.listSourceDecisions));
resolver.define('tm:sources:prepareDecision', cached(coverage.prepareSourceDecision));
resolver.define('tm:sources:signDecision', cached(coverage.signSourceDecision));
resolver.define('tm:sources:finishDecision', cached(coverage.finishSourceDecision));
resolver.define('tm:sources:getDecision', cached(coverage.getSourceDecision));
resolver.define('tm:summary:generate', cached(summary.generateExecutionSummary));
resolver.define('tm:summary:read', cached(summary.readExecutionSummary));

export const handler = wrapWithHarness(resolver.getDefinitions(), { resolverName: 'testManagement' });
