import { canonical } from '../hash.js';

/**
 * Describe structural differences between paired ADF blocks. Compare node
 * attrs, enclosing containers and inline nodes other than text. adf.js handles
 * block pairing, words and marks.
 */

/** ADF stores a date as epoch milliseconds, as a string. Shown as the day. */
export function dateText(timestamp) {
  const ms = Number(timestamp);
  return Number.isFinite(ms) ? new Date(ms).toISOString().slice(0, 10) : '[date]';
}

/** What a reviewer calls each node. Anything unlisted is shown by its ADF name. */
const LABELS = {
  paragraph: 'Paragraph', heading: 'Heading', blockquote: 'Quote', codeBlock: 'Code block',
  rule: 'Divider', panel: 'Panel', bulletList: 'Bulleted list', orderedList: 'Numbered list',
  listItem: 'List item', taskList: 'Checklist', taskItem: 'Checklist item',
  decisionList: 'Decision list', decisionItem: 'Decision', table: 'Table', tableRow: 'Table row',
  tableCell: 'Cell', tableHeader: 'Header cell', expand: 'Expand', nestedExpand: 'Expand',
  mediaSingle: 'Image', mediaGroup: 'Files', media: 'Attachment', layoutSection: 'Layout',
  layoutColumn: 'Layout column', blockCard: 'Link card', embedCard: 'Embed',
  inlineCard: 'Link card', status: 'Status', date: 'Date', mention: 'Mention', emoji: 'Emoji'
};

/** Attr names as a reviewer would say them, per node type where it differs. */
const ATTR_LABELS = {
  panelType: 'type', order: 'start number', level: 'level', language: 'language',
  title: 'title', color: 'colour', timestamp: 'date', layout: 'layout', width: 'width',
  isNumberColumnEnabled: 'row numbers', background: 'background', colspan: 'column span',
  rowspan: 'row span', colwidth: 'column widths', url: 'address', id: 'id', shortName: 'name'
};

const label = (type) => LABELS[type] ?? type ?? 'Block';

function describeNode(type, attrs) {
  if (type === 'taskItem') return `Checklist item (${attrs?.state === 'DONE' ? 'ticked' : 'unticked'})`;
  if (type === 'decisionItem') return `Decision (${String(attrs?.state ?? 'UNDECIDED').toLowerCase()})`;
  if (type === 'heading' && attrs?.level != null) return `Heading ${attrs.level}`;
  if (type === 'panel' && attrs?.panelType) return `Panel (${attrs.panelType})`;
  return label(type);
}

function showValue(key, value) {
  if (value === undefined || value === null) return '(none)';
  if (key === 'timestamp') return dateText(value);
  return typeof value === 'object' ? canonical(value) : String(value);
}

/**
 * One sentence per attr that differs on one node. `localId` is not compared:
 * normaliseAdf has already stripped it, and it is regenerated by Jira anyway.
 */
function attrChanges(type, before, after) {
  const a = before ?? {};
  const b = after ?? {};
  const out = [];
  for (const key of [...new Set([...Object.keys(a), ...Object.keys(b)])].sort()) {
    if (key === 'localId' || canonical(a[key] ?? null) === canonical(b[key] ?? null)) continue;
    if ((type === 'taskItem' || type === 'decisionItem') && key === 'state') {
      out.push({ kind: 'state', node: type, key, from: a[key] ?? null, to: b[key] ?? null,
        text: type === 'taskItem'
          ? `Checklist item ${b[key] === 'DONE' ? 'ticked' : 'unticked'}`
          : `Decision ${String(a[key] ?? '(none)').toLowerCase()} → ${String(b[key] ?? '(none)').toLowerCase()}` });
      continue;
    }
    out.push({ kind: 'attr', node: type, key, from: a[key] ?? null, to: b[key] ?? null,
      text: `${label(type)} ${ATTR_LABELS[key] ?? key}: ${showValue(key, a[key])} → ${showValue(key, b[key])}` });
  }
  return out;
}

const containerPath = (list) => list.map((c) => describeNode(c.type, c.attrs)).join(' › ');

/**
 * The containers around a block, before and after.
 *
 * Matched from both ends: a common prefix and a common suffix of container
 * TYPES are the same containers, so only their attrs are compared; whatever is
 * left in the middle was swapped, removed or added. A bulleted list renumbered
 * reads "Bulleted list → Numbered list", not the whole path twice.
 */
function contextChanges(before = [], after = []) {
  const out = [];
  let head = 0;
  while (head < before.length && head < after.length && before[head].type === after[head].type) {
    out.push(...attrChanges(before[head].type, before[head].attrs, after[head].attrs));
    head++;
  }
  let tail = 0;
  while (tail < before.length - head && tail < after.length - head
    && before[before.length - 1 - tail].type === after[after.length - 1 - tail].type) {
    const x = before[before.length - 1 - tail];
    const y = after[after.length - 1 - tail];
    out.push(...attrChanges(x.type, x.attrs, y.attrs));
    tail++;
  }
  const removed = before.slice(head, before.length - tail);
  const added = after.slice(head, after.length - tail);
  if (removed.length && added.length) {
    out.push({ kind: 'container', text: `${containerPath(removed)} → ${containerPath(added)}` });
  } else if (removed.length) {
    out.push({ kind: 'container', text: `Taken out of ${containerPath(removed)}` });
  } else if (added.length) {
    out.push({ kind: 'container', text: `Put into ${containerPath(added)}` });
  }
  return out;
}

/** Inline nodes that are not text, in order: lozenges, dates, mentions, cards, media. */
function inlineAtoms(node) {
  const out = [];
  const walk = (n) => {
    if (!n || typeof n !== 'object') return;
    if (Array.isArray(n)) { n.forEach(walk); return; }
    if (n.type !== 'text' && !Array.isArray(n.content) && n !== node) {
      out.push({ type: n.type, attrs: n.attrs ?? {} });
      return;
    }
    walk(n.content);
  };
  walk(node?.content);
  return out;
}

function inlineChanges(beforeNode, afterNode) {
  const a = inlineAtoms(beforeNode);
  const b = inlineAtoms(afterNode);
  if (canonical(a) === canonical(b)) return [];
  const out = [];
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const x = a[i];
    const y = b[i];
    if (!x) out.push({ kind: 'inline', text: `${label(y.type)} added` });
    else if (!y) out.push({ kind: 'inline', text: `${label(x.type)} removed` });
    else if (x.type !== y.type) out.push({ kind: 'inline', text: `${label(x.type)} → ${label(y.type)}` });
    else out.push(...attrChanges(x.type, x.attrs, y.attrs).map((c) => ({ ...c, kind: 'inline' })));
  }
  return out;
}

/**
 * Everything that differs between two paired blocks except their words and
 * marks, as sentences. Empty when the two are the same apart from those.
 */
export function describeStructure(del, ins) {
  if (!del || !ins || del.sig === ins.sig) return [];
  const out = [];
  if (del.type !== ins.type) {
    out.push({ kind: 'type', from: del.type, to: ins.type,
      text: `${describeNode(del.type, del.attrs)} → ${describeNode(ins.type, ins.attrs)}` });
  } else {
    out.push(...attrChanges(del.type, del.attrs, ins.attrs));
  }
  out.push(...contextChanges(del.context, ins.context));
  // A table row's cells are compared by diffCells; their inline atoms would
  // only repeat it.
  if (del.type !== 'tableRow') out.push(...inlineChanges(del.node, ins.node));
  return out;
}
